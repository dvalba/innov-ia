"""Validation router (T-034, RF-14/RF-15/RF-16; T-074, RF-26; T-082, RF-27/RF-28).

Specialist review surface, all guarded to the `especialista` role (403
otherwise):
  GET  /validation/queue          -> 200 the review queue by stage (RF-14, v2.2:
                                         `publicacion` / `calibracion` / both;
                                         proponent without contact; 422 stage
                                         invalid)
  POST /validation/{id}/approve   -> 200 payload (VALIDADA_PUBLICA, rastro +
                                         `IDEA_PUBLISHED`; the debate opens and
                                         the AI evaluation is generated at the
                                         debate's closure, RF-26)
  POST /validation/{id}/reject    -> 200 payload (EN_DESARROLLO, comentario +
                                         `IDEA_REJECTED`; 400 sin comentario)
  POST /validation/{id}/evaluation/accept -> 200 payload (la evaluación de la
                                         IA queda como juicio final; 409 si no
                                         existe la evaluación de la IA)
  POST /validation/{id}/evaluation        -> 200 payload (sustitución por la
                                         del especialista; 422 si faltan
                                         criterios o el score está fuera de rango)
  POST /validation/{id}/decision  -> 200 {state, decision} (decisión final de la
                                         calificación, RF-27/RF-28; 409 si el
                                         outcome no coincide con la banda del
                                         promedio o no está en
                                         VALIDADA_PUBLICA, 400 sin motivo en
                                         ARCHIVADA/RECHAZADA)

The approve/reject/decision endpoints do NOT reimplement the transition: they
reuse the `ideas` use cases / state machine, preserving the audit trail and the
emission points. The emitted notifications and the on-publish debate opener are
wired in the composition root (`app/deps`) so this feature imports only `ideas`;
the AI evaluation is generated by the `debate` feature at the closure (T-074,
RF-26). The calibration queue's debate-closure predicate is built here from the
injected `DebateStore` (this feature never imports `debate`).
"""

from fastapi import APIRouter
from pydantic import BaseModel

from app.deps import (
    DebateOpenDep,
    DebateStoreDep,
    DecisionEmitterDep,
    IdeaLedgerDep,
    PublishedEmitterDep,
    RejectedEmitterDep,
    ThresholdStoreDep,
    UserDirectoryDep,
    role_dependency,
)
from features.ideas.use_cases.approve_idea import approve_idea
from features.ideas.use_cases.reject_idea import reject_idea
from features.validation.use_cases.accept_ai_evaluation import accept_ai_evaluation
from features.validation.use_cases.decide_final import decide_final
from features.validation.use_cases.replace_evaluation import replace_evaluation
from features.validation.use_cases.review_queue import queue
from shared.contracts.user_directory import UserDirectory

validation_router = APIRouter(prefix="/validation", tags=["validation"])

SpecialistDep = role_dependency("especialista")


class RejectRequest(BaseModel):
    comment: str = ""


class DecisionRequest(BaseModel):
    """The final calibration decision (RF-27): `outcome` + `reason`.

    `reason` is mandatory for `ARCHIVADA`/`RECHAZADA` and an optional note for
    `ACEPTADA` (the domain enforces it, case 28).
    """

    outcome: str
    reason: str | None = None


class EvaluationCriterionIn(BaseModel):
    """One of the 5 fixed criteria (RF-26): the domain re-validates the set."""

    criterion: str
    score: int
    justification: str


class EvaluationReplaceRequest(BaseModel):
    """The specialist's replacement judgment: the same 5 fixed criteria (RF-26)."""

    criteria: list[EvaluationCriterionIn]


def _specialist_name(directory: UserDirectory, session) -> str:
    user = directory.get(session.user_id)
    return user.get("name", "") if user is not None else ""


def _is_debate_closed(debate_store, idea_id: str) -> bool:
    """True when the idea has a debate record and it is closed (RF-14 v2.2)."""
    record = debate_store.get(idea_id)
    return bool(record) and bool(record.get("closed"))


@validation_router.get("/queue")
def queue_endpoint(session: SpecialistDep, ledger: IdeaLedgerDep,
                   debate_store: DebateStoreDep,
                   stage: str | None = None) -> list[dict]:
    """Lists the review queue by stage (RF-14, v2.2).

    `stage=publicacion` -> ideas in SOLICITANDO_PUBLICACION; `stage=calibracion`
    -> published ideas whose debate is closed and whose evaluation is not
    `PENDING` (and which carry no decision yet); no `stage` -> both, publication
    first. A stage outside those two is a 422 `QUEUE_STAGE_INVALID`.
    """
    return queue(ledger, stage,
                 is_debate_closed=lambda idea_id: _is_debate_closed(debate_store, idea_id))


@validation_router.post("/{idea_id}/approve")
def approve_endpoint(idea_id: str, session: SpecialistDep, ledger: IdeaLedgerDep,
                     directory: UserDirectoryDep, emit: PublishedEmitterDep,
                     open_debate_now: DebateOpenDep) -> dict:
    """Approves/publishes the idea, reusing `approve_idea` (G06) + `IDEA_PUBLISHED`.

    Publishing opens the idea's debate with a `30-day` deadline (RF-24, T-073).
    The AI evaluation on the 5 fixed criteria (RF-26, T-074) is generated at
    the debate's closure, not at the publication: a down assistant keeps it
    `PENDING` without ever blocking (case 22). The debate opener is wired in
    the composition root so `validation` keeps importing only `ideas`.
    """
    payload = approve_idea(ledger, idea_id=idea_id, user_id=session.user_id,
                            user_name=_specialist_name(directory, session),
                            user_roles=session.roles, emit_notification=emit)
    open_debate_now(payload)
    return payload


@validation_router.post("/{idea_id}/reject")
def reject_endpoint(idea_id: str, payload: RejectRequest, session: SpecialistDep,
                    ledger: IdeaLedgerDep, directory: UserDirectoryDep,
                    emit: RejectedEmitterDep) -> dict:
    """Rejects the idea (400 sin comentario, caso 13), reusing `reject_idea` (G06).

    The comment itself may be blank; `reject_idea` then raises the domain 400
    `REJECTION_COMMENT_REQUIRED` (case 13).
    """
    return reject_idea(ledger, idea_id=idea_id, user_id=session.user_id,
                       user_name=_specialist_name(directory, session),
                       user_roles=session.roles, comment=payload.comment,
                       emit_notification=emit)


@validation_router.post("/{idea_id}/evaluation/accept")
def accept_evaluation_endpoint(idea_id: str, session: SpecialistDep, ledger: IdeaLedgerDep) -> dict:
    """Accepts the AI evaluation as the final judgment (RF-26, caso 23).

    The `aiEvaluation` snapshot becomes `evaluation` with `status=ACEPTADA`
    and the specialist's decision audit (RNF-8). 409 when there is no AI
    evaluation yet (still `PENDING`, case 22: nothing to accept). The
    decision may follow a replacement — last action wins (case 23).
    """
    return accept_ai_evaluation(ledger, idea_id=idea_id, user_id=session.user_id)


@validation_router.post("/{idea_id}/evaluation")
def replace_evaluation_endpoint(idea_id: str, payload: EvaluationReplaceRequest,
                                session: SpecialistDep, ledger: IdeaLedgerDep,
                                directory: UserDirectoryDep) -> dict:
    """Replaces the final judgment with the specialist's own (RF-26, caso 23).

    The same 5 fixed criteria (RNF-5: missing/unknown/duplicated criteria or
    a score out of 1-10 -> 422 with the problems in `details`). No state
    guard: it applies before or after accepting the AI's evaluation; the
    judgment is the result of the last action (case 23) and the AI snapshot
    stays visible untouched (RF-26).
    """
    return replace_evaluation(
        ledger, idea_id=idea_id, user_id=session.user_id,
        user_name=_specialist_name(directory, session),
        criteria=[item.model_dump() for item in payload.criteria],
    )


@validation_router.post("/{idea_id}/decision")
def decision_endpoint(idea_id: str, payload: DecisionRequest, session: SpecialistDep,
                      ledger: IdeaLedgerDep, directory: UserDirectoryDep,
                      thresholds: ThresholdStoreDep, emit: DecisionEmitterDep) -> dict:
    """Takes the final calibration decision (RF-27/RF-28).

    `outcome` (ACEPTADA/ARCHIVADA/RECHAZADA) must match the band of the average
    of the 5 criteria (409 `DECISION_MISMATCH` carrying `score`/`band`, case 27)
    and `ARCHIVADA`/`RECHAZADA` require a reason (400, case 28). Only a
    `VALIDADA_PUBLICA` idea with a current (non-`PENDING`) evaluation admits it
    (409). The decision is audited (RNF-8) and the creator notified (RF-18).
    """
    return decide_final(
        ledger, thresholds, idea_id=idea_id, outcome=payload.outcome,
        reason=payload.reason, user_id=session.user_id,
        user_name=_specialist_name(directory, session), user_roles=session.roles,
        emit_notification=emit,
    )
